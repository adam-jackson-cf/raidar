"""Assessor-owned file inventory (plan F3): agent-written exclusions never hide code."""

from __future__ import annotations

import os
from pathlib import Path

from raidar.oracle.models import CaseStatus
from raidar.scorers.inventory import (
    GENERATED_MARKER_CLAIM,
    INVALID_EVIDENCE,
    FileRole,
    InventoryPolicy,
    build_inventory,
    matches_glob,
)
from raidar.scorers.rescore import rescore_path
from raidar.scorers.store import AssessmentStore
from tests.scorer_support import StepFixture, fake_registry, write_files, write_trial

HIDING_SNAPSHOT = {
    ".gitignore": "app/secret/\n*.py\n",
    "app/core.py": "def core():\n    return 1\n",
    "app/secret/impl.py": "def hidden_by_gitignore():\n    return 2\n",
    "app/marked.py": "# @generated by hand\ndef hidden_by_marker():\n    return 3\n",
    "app/lizard_marked.py": "# GENERATED CODE -- DO NOT EDIT\ndef also_hidden():\n    return 4\n",
    "app/proto/schema.py": "SCHEMA = {}\n",
    "tests/test_core.py": "def test_core():\n    assert True\n",
    "README.md": "# toy\n",
    "__pycache__/cached.py": "x = 1\n",
    ".venv/lib/site.py": "y = 2\n",
}


def _snapshot(root: Path) -> Path:
    write_files(root, HIDING_SNAPSHOT)
    (root / "app" / "latin1.py").write_bytes("s = 'caf\xe9'\n".encode("latin-1"))
    os.symlink("core.py", root / "app" / "alias.py")
    return root


def test_code_hidden_by_gitignore_or_generated_markers_is_still_counted(tmp_path: Path) -> None:
    inventory = build_inventory(
        _snapshot(tmp_path / "app"), InventoryPolicy(generated_globs=("app/proto/**",))
    )
    roles = {item.path: item.role for item in inventory.files}
    assert roles["app/core.py"] is FileRole.PRODUCTION
    assert roles["app/secret/impl.py"] is FileRole.PRODUCTION
    assert roles["app/marked.py"] is FileRole.PRODUCTION
    assert roles["app/lizard_marked.py"] is FileRole.PRODUCTION
    assert roles["tests/test_core.py"] is FileRole.TEST
    # Only an assessor-owned glob makes a file generated.
    assert roles["app/proto/schema.py"] is FileRole.GENERATED

    claims = {item.path: item.agent_claims for item in inventory.files if item.agent_claims}
    assert claims == {
        "app/marked.py": (GENERATED_MARKER_CLAIM,),
        "app/lizard_marked.py": (GENERATED_MARKER_CLAIM,),
    }


def test_every_file_left_out_of_measurement_is_listed_with_a_reason(tmp_path: Path) -> None:
    inventory = build_inventory(_snapshot(tmp_path / "app"))
    reasons = {item.path: item.reason for item in inventory.exclusions}
    assert reasons == {
        ".gitignore": "extensionless",
        ".venv": "snapshot_exclude:.venv",
        "README.md": "unrecognized_extension",
        "__pycache__": "snapshot_exclude:__pycache__",
        "app/latin1.py": "non_utf8",
    }
    measured = {item.path for item in inventory.files if item.role is not FileRole.IGNORED}
    assert measured.isdisjoint(reasons)
    # An in-snapshot symlink is measured under its own path with its target's bytes.
    alias = next(item for item in inventory.files if item.path == "app/alias.py")
    core = next(item for item in inventory.files if item.path == "app/core.py")
    assert (alias.role, alias.resolved_path, alias.sha256) == (
        FileRole.PRODUCTION,
        "app/core.py",
        core.sha256,
    )


def test_unreadable_evidence_makes_the_inventory_ineligible_instead_of_shrinking_it(
    tmp_path: Path,
) -> None:
    outside = tmp_path / "outside"
    write_files(outside, {"lib.py": "x = 1\n", "pkg/mod.py": "y = 2\n"})
    root = tmp_path / "app"
    write_files(root, {"app/core.py": "def core():\n    return 1\n", "app/pkg/m.py": "z = 3\n"})
    assert build_inventory(root).eligible
    os.symlink("pkg", root / "app" / "pkg_alias")
    inventory = build_inventory(root)
    assert inventory.eligible
    assert {e.path: e.reason for e in inventory.exclusions} == {
        "app/pkg_alias": "symlink_to_directory"
    }

    (root / "app" / "latin1.py").write_bytes("s = 'caf\xe9'\n".encode("latin-1"))
    os.symlink(outside / "lib.py", root / "app" / "lib.py")
    os.symlink(outside / "pkg", root / "app" / "vendor")
    os.symlink("missing.py", root / "app" / "gone.py")
    os.symlink("missing.md", root / "NOTES.md")
    inventory = build_inventory(root)
    assert not inventory.eligible
    assert {(issue.path, issue.code) for issue in inventory.invalid} == {
        (path, INVALID_EVIDENCE)
        for path in ("app/latin1.py", "app/lib.py", "app/vendor", "app/gone.py", "NOTES.md")
    }
    measured = {item.path for item in inventory.with_role(FileRole.PRODUCTION)}
    assert measured == {"app/core.py", "app/pkg/m.py"}


def test_inventory_is_deterministic_regardless_of_creation_order(tmp_path: Path) -> None:
    forward = tmp_path / "forward"
    write_files(forward, HIDING_SNAPSHOT)
    backward = tmp_path / "backward"
    write_files(backward, dict(reversed(list(HIDING_SNAPSHOT.items()))))
    assert build_inventory(forward) == build_inventory(backward)
    assert build_inventory(forward).digest() == build_inventory(backward).digest()


def test_assessor_globs_are_anchored_to_the_full_path() -> None:
    assert matches_glob("app/proto/schema.py", "app/proto/**")
    assert matches_glob("app/proto/deep/x.py", "app/**/*.py")
    assert not matches_glob("app/proto/deep/x.py", "app/proto/*.py")
    assert not matches_glob("vendor/app/proto/x.py", "app/proto/**")


def test_scorers_see_hidden_code_through_the_context_inventory(tmp_path: Path) -> None:
    files = {k: v for k, v in HIDING_SNAPSHOT.items() if not k.startswith(("__", ".venv"))}
    trial = write_trial(
        tmp_path / "trial", [StepFixture("checkpoint_1", files, (CaseStatus.PASSED,))]
    )
    store = AssessmentStore(tmp_path / "store")
    (record,) = rescore_path(trial, ["fake-quality@1"], store, fake_registry())
    assessment = store.get(record.key)
    assert assessment is not None
    counted = {
        o.subject: o.value for o in assessment.result.observations if o.metric == "production_files"
    }
    # core, secret/impl, marked, lizard_marked and proto/schema (no assessor glob here).
    assert counted == {"checkpoint_1": 5}
    evidence = {e.path for e in assessment.result.evidence}
    assert {"app/secret/impl.py", "app/marked.py"} <= evidence
    assert all(loc.endswith(":1") for e in assessment.result.evidence for loc in e.locations())
