def test_the_state_an_aspect_is_asked_on_is_the_criterion_the_aspect_and_the_tests() -> None:
    item = criterion("F1.AC1", ("a JSON array is parsed", "ValueError is raised"))

    context = judging.assemble(subject(item, REJECTS), PASSING, FILES.get, 32_000)

    (request,) = context.requests
    assert request.aspect == "F1.AC1.A1"
    state = request.state
    assert state["criterion"] == {"id": "F1.AC1", "text": item.text}
    assert state["aspect"] == {
        "situation": "a JSON array is parsed",
        "outcome": "ValueError is raised",
    }
    (entry,) = state["tests"]
    assert (entry["id"], entry["gate_result"], entry["file"], entry["lines"]) == (
        REJECTS,
        "passed",
        "tests/test_app.py",
        [19, 21],
    )
    assert entry["source"].splitlines()[0] == "   19  def test_parse_rejects(raw):"
    assert [helper["name"] for helper in entry["helpers"]] == ["raw"]
    assert "production" not in json.dumps(state)
    assert (context.cut, context.opened, context.tests_ok) == (False, (), True)


