# --- stopping ---------------------------------------------------------------------


def result(number: int, *statuses: str, tests: tuple[str, ...] = (OBJECT,)) -> judging.PassResult:
    outcomes = []
    for index, status in enumerate(statuses, start=1):
        item = criterion(f"F1.AC{index}", ("s", "o"))
        answer = {"closed": 0.9, "open": 0.1, "undecided": 0.5}[status]
        outcomes.append(outcome_for(item, tests, {f"F1.AC{index}.A1": answer}))
    return judging.PassResult(number, tuple(outcomes))


def test_the_loop_is_verified_only_when_every_criterion_is_closed_over_an_accepted_gate() -> None:
    history = [result(1, "closed", "closed")]

    assert judging.stop_reason(history, SETTINGS, 3, None, True) == "verified"
    assert judging.stop_reason(history, SETTINGS, 3, ["a.py"], False) is None
    assert judging.stop_reason(history, SETTINGS, 3, [], False) == "no_progress"
    assert judging.stop_reason([result(3, "closed")], SETTINGS, 3, ["a.py"], False) == "pass_limit"


def test_a_pass_over_no_criteria_is_never_verified() -> None:
    empty = judging.PassResult(1, ())

    assert judging.stop_reason([empty], SETTINGS, 3, None, True) == "no_progress"
    assert judging.stop_reason([empty], SETTINGS, 3, ["a.py"], True) == "no_progress"


def test_an_open_or_undecided_criterion_sends_the_loop_to_rework_until_the_pass_limit() -> None:
    assert judging.stop_reason([result(1, "closed", "open")], SETTINGS, 3, None, True) is None
    assert judging.stop_reason([result(1, "undecided")], SETTINGS, 3, None, True) is None
    assert judging.stop_reason([result(3, "open")], SETTINGS, 3, ["a.py"], True) == "pass_limit"


def test_nothing_closed_nothing_changed_and_no_remap_is_no_progress() -> None:
    history = [result(1, "open"), result(2, "open")]

    assert judging.stop_reason(history, SETTINGS, 5, [], True) == "no_progress"
    assert judging.stop_reason(history, SETTINGS, 5, ["calc.py"], True) is None
    newly = [result(1, "open"), result(2, "closed")]
    assert not judging.stalled(newly, SETTINGS, [])
    remapped = [result(1, "open"), result(2, "open", tests=(REJECTS,))]
    assert not judging.stalled(remapped, SETTINGS, [])


def test_the_same_failures_for_stall_repeats_plus_one_passes_are_no_progress() -> None:
    history = [result(number, "open") for number in (1, 2, 3)]

    assert judging.stalled(history, SETTINGS, ["calc.py"])
    assert not judging.stalled(history[:2], SETTINGS, ["calc.py"])
    assert not judging.stalled([result(1, "open")], SETTINGS, [])


