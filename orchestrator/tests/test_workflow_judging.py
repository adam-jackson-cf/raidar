def test_the_pushback_shows_the_issues_words_the_aspects_not_closed_and_the_tests_results() -> None:
    first = criterion("F1.AC1", ("a JSON array is parsed", "ValueError is raised"))
    second = criterion("F1.AC2", ("s", "o"))
    outcomes = (
        outcome_for(first, (REJECTS,), {"F1.AC1.A1": 0.12}),
        outcome_for(second, (OBJECT,), {"F1.AC2.A1": 0.95}),
    )

    text = judging.pushback_text(judging.PassResult(1, outcomes))

    assert text == "\n".join(
        [
            "## F1 Parsing",
            "",
            "### F1.AC1: parse rejects a JSON value that is not an object",
            "",
            "The issue's words:",
            "> Reject any document that is not a JSON object",
            "",
            "Status: open. What is missing:",
            "- F1.AC1.A1 (p 0.12): no test sets up a JSON array is parsed and asserts "
            "ValueError is raised",
            f"Mapped tests: `{REJECTS}` (passed)",
        ]
    )


