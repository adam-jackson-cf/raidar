TESTS = """\
import pytest

from app import parse


def sample():
    return '{"a": 1}'


@pytest.fixture
def raw():
    return "[]"


def test_parse_object():
    assert parse(sample()) == {"a": 1}


def test_parse_rejects(raw):
    with pytest.raises(ValueError):
        parse(raw)


def test_wrapper():
    test_parse_object()


class TestGroup:
    def setUp(self):
        self.value = 1

    def helper(self):
        return self.value

    def test_method(self):
        assert self.helper() == 1
"""
OBJECT = "tests/test_app.py::test_parse_object"
REJECTS = "tests/test_app.py::test_parse_rejects"
WRAPPER = "tests/test_app.py::test_wrapper"
METHOD = "tests/test_app.py::TestGroup::test_method"
COLLECTED = [OBJECT, REJECTS, WRAPPER, METHOD]
PASSING = {"collected": COLLECTED, "outcomes": dict.fromkeys(COLLECTED, "passed")}
FILES = {"tests/test_app.py": TESTS}
SETTINGS = JudgeConfig(model="typesafe/jev-1.13-20260917", closed_at=0.8, open_at=0.3)


def criterion(
    ident: str = "F1.AC1",
    *pairs: tuple[str, str],
    kind: str = "",
    examples: tuple[Example, ...] = (),
) -> Criterion:
    aspects = tuple(
        Aspect(f"{ident}.A{number}", situation, outcome)
        for number, (situation, outcome) in enumerate(pairs, start=1)
    )
    return Criterion(
        ident,
        "parse rejects a JSON value that is not an object",
        sources=("Reject any document that is not a JSON object",),
        aspects=aspects,
        examples=examples,
        kind=kind,
    )


def subject(item: Criterion, *tests: str) -> judging.Subject:
    return judging.Subject(item, "F1", "Parsing", tests)


