def criterion(
    ident: str = "F1.AC1",
    *pairs: tuple[str, str],
    kind: str = "",
    examples: tuple[Example, ...] = (),
) -> Criterion:
    aspects = tuple(
        Aspect(f"{ident}.A{number}", situation, outcome)
        for number, (situation, outcome) in enumerate(pairs, start=1)
    )
    return Criterion(
        ident,
        "parse rejects a JSON value that is not an object",
        sources=("Reject any document that is not a JSON object",),
        aspects=aspects,
        examples=examples,
        kind=kind,
    )


def subject(item: Criterion, *tests: str) -> judging.Subject:
    return judging.Subject(item, "F1", "Parsing", tests)


