"""The per-step ``setup.sh`` (requirements F3) and the check that it ran.

Every trial's every step gets one. Harbor runs it as the agent user after the step's workdir
upload and before the agent starts. The script:

1. runs the context reset (``step_reset.sh``): kill leftover agent-user processes, reset
   harness state to the harness baseline, write ``raidar-reset.json`` to the agent logs;
2. deletes itself from the workspace, or puts back the agent's own ``setup.sh`` that the step
   upload overwrote (stashed by the agent-end reaper, ``raidar.engine.health.reaper``).

``reset_check`` reads one archived step's ``raidar-reset.json``: the step is infra-invalid
unless the reset ran, was not refused, left no agent-user process and reset every state path.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from importlib.resources import files
from pathlib import Path

SETUP_SCRIPT_NAME = "setup.sh"
RESET_REPORT = "raidar-reset.json"

# Where the agent-end reaper keeps a copy of an agent-authored ``/app/setup.sh``.
AGENT_SETUP_STASH = "/tmp/.raidar-agent-setup.sh"


def reset_body() -> str:
    return files("raidar.engine.health").joinpath("step_reset.sh").read_text(encoding="utf-8")


def render_setup_script() -> str:
    """The whole ``setup.sh``: the context reset, then never leave the script in ``/app``."""
    return "\n".join(
        [
            "#!/usr/bin/env bash",
            "# Generated by raidar.engine.health.setup_script; do not edit.",
            "set -uo pipefail",
            reset_body(),
            "# ---- never leave this script in the agent's workspace ----------------------",
            "# The upload overwrote any agent-authored setup.sh; the agent-end reaper",
            "# stashed that file, so it is put back instead of being deleted (F3).",
            f'RAIDAR_AGENT_SETUP_STASH="${{RAIDAR_AGENT_SETUP_STASH:-{AGENT_SETUP_STASH}}}"',
            'if [ "${RAIDAR_RESET_KEEP_SELF:-0}" != "1" ]; then',
            '  if [ -f "$RAIDAR_AGENT_SETUP_STASH" ]; then',
            '    cp -- "$RAIDAR_AGENT_SETUP_STASH" "$0" 2>/dev/null || rm -f -- "$0" 2>/dev/null',
            '  else rm -f -- "$0" 2>/dev/null; fi',
            "fi",
            "exit 0",
            "",
        ]
    )


def write_setup_scripts(task_dir: Path, step_names: list[str]) -> None:
    """Write each step's ``workdir/setup.sh``; refuse a task that ships its own."""
    if not step_names:
        raise ValueError("a task needs at least one step for the per-step reset")
    script = render_setup_script().encode()
    for step in step_names:
        target = task_dir / "steps" / step / "workdir" / SETUP_SCRIPT_NAME
        if target.exists():
            raise FileExistsError(f"{target} already exists; the task owns that path")
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(script)
        target.chmod(0o755)


@dataclass(frozen=True)
class ResetOutcome:
    passed: bool
    detail: str


def reset_check(agent_dir: Path) -> ResetOutcome:
    """The step's reset ran, was not refused, and left no process or state behind."""
    try:
        report = json.loads((agent_dir / RESET_REPORT).read_text())
    except (OSError, ValueError):
        return ResetOutcome(False, f"no readable {RESET_REPORT}: setup.sh did not run")
    if report.get("error"):
        return ResetOutcome(False, f"reset refused: {report['error']}")
    residual = report.get("residual") or []
    failed = [entry.get("path") for entry in report.get("state", []) if entry.get("reset_failed")]
    if residual or failed:
        return ResetOutcome(False, f"residual processes {residual}; state not reset {failed}")
    killed = len(report.get("killed") or [])
    return ResetOutcome(True, f"reset ok; killed {killed} leftover process(es)")
