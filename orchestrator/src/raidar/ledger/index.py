"""Deterministic ``lab/ledger/README.md``: faults and remedies by status, with links."""

from __future__ import annotations

from raidar.ledger.records import (
    FAULT_STATUSES,
    REMEDY_STATUSES,
    FaultRecord,
    RemedyRecord,
)

README_NAME = "README.md"

_INTRO = """# Ledger

Generated by `make ledger-index`; do not edit. Checked by `make ledger-check`.

Records are Markdown files with YAML frontmatter: fault categories in `faults/FCR-NNN.md`
and remedies in `remedies/M-NNN.md`. Procedure lives in the `fault-catalog` skill.
"""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _fault_row(fault: FaultRecord) -> str:
    target = _cell(fault.target) if fault.target else "—"
    return (
        f"| [{fault.id}](faults/{fault.id}.md) | {_cell(fault.title)} | {fault.category} "
        f"| {_cell(fault.owner)} | {fault.status_history[0].date} | {target} |"
    )


def _remedy_row(remedy: RemedyRecord) -> str:
    faults = ", ".join(f"[{f}](faults/{f}.md)" for f in sorted(remedy.faults))
    return (
        f"| [{remedy.id}](remedies/{remedy.id}.md) | {_cell(remedy.title)} | {faults} "
        f"| {_cell(remedy.lever)} | {_cell(remedy.home)} |"
    )


def _section(title: str, header: str, rows: list[str]) -> list[str]:
    if not rows:
        return []
    columns = header.count("|") - 1
    return ["", f"### {title}", "", header, "|" + "---|" * columns, *rows]


def render_index(faults: dict[str, FaultRecord], remedies: dict[str, RemedyRecord]) -> str:
    lines = [_INTRO.rstrip("\n"), "", "## Faults"]
    fault_header = "| ID | Fault category | Category | Owner | First recorded | Target |"
    for status in FAULT_STATUSES:
        rows = [_fault_row(f) for _, f in sorted(faults.items()) if f.status == status]
        lines += _section(f"`{status}`", fault_header, rows)
    if not faults:
        lines += ["", "None."]
    lines += ["", "## Remedies"]
    remedy_header = "| ID | Remedy | Faults | Lever | Home |"
    for status in REMEDY_STATUSES:
        rows = [_remedy_row(r) for _, r in sorted(remedies.items()) if r.status == status]
        lines += _section(f"`{status}`", remedy_header, rows)
    if not remedies:
        lines += ["", "None."]
    return "\n".join(lines) + "\n"
