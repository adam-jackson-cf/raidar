"""Generate the per-step ``setup.sh`` (requirements F3, F5).

Every arm gets one, with or without components. The script:

1. runs the context reset (``step_reset.sh``): kill leftover agent-user
   processes, reset harness state to the Condition baseline;
2. materialises component support files under ``/tmp/raidar-components``
   (never inside the workspace);
3. records the sha256 of every overlay path in the workspace at step start,
   the environment evidence for workspace discovery probes;
4. deletes itself from the workspace, or puts back the agent's own
   ``setup.sh`` that the step upload overwrote (stashed by the agent-end
   reaper, ``raidar.execution.reaper``).
"""

from __future__ import annotations

import base64
import re
import shlex
from collections.abc import Iterable, Mapping
from importlib.resources import files
from pathlib import PurePosixPath

from raidar.components.definition.contribution import COMPONENT_ROOT, EVIDENCE_DIR, SupportFile
from raidar.components.definition.evidence import COMPONENT_REPORT

SETUP_SCRIPT_NAME = "setup.sh"
SAFE_PATH_RE = re.compile(r"^[A-Za-z0-9._@+-]+(/[A-Za-z0-9._@+-]+)*$")
_HEREDOC = "RAIDAR_COMPONENT_FILE"

# Where the agent-end reaper keeps a copy of an agent-authored ``/app/setup.sh``.
AGENT_SETUP_STASH = "/tmp/.raidar-agent-setup.sh"


def reset_body() -> str:
    return files("raidar.components.runtime").joinpath("step_reset.sh").read_text(encoding="utf-8")


def _check_relative(relative: str, what: str) -> None:
    if not SAFE_PATH_RE.fullmatch(relative) or ".." in relative.split("/"):
        raise ValueError(f"unsafe {what} path {relative!r}")


def _materialise(relative: str, support: SupportFile) -> list[str]:
    """Write one support file below ``$RAIDAR_COMPONENT_ROOT`` (``/tmp/raidar-components``)."""
    _check_relative(relative, "component support file")
    encoded = base64.b64encode(support.content).decode("ascii")
    wrapped = "\n".join(encoded[i : i + 76] for i in range(0, len(encoded), 76))
    target = f'"$RAIDAR_COMPONENT_ROOT"/{shlex.quote(relative)}'
    parent = PurePosixPath(relative).parent.as_posix()
    lines = [
        f'mkdir -p -- "$RAIDAR_COMPONENT_ROOT"/{shlex.quote(parent)}',
        f"base64 -d > {target} <<'{_HEREDOC}'",
        wrapped,
        _HEREDOC,
    ]
    if support.executable:
        lines.append(f"chmod 755 {target}")
    return lines


def _workspace_evidence(paths: Iterable[str]) -> list[str]:
    lines = ['files_json=""']
    for relative in sorted(paths):
        quoted = shlex.quote(relative)
        lines += [
            f'if [ -f "$RAIDAR_WORKSPACE"/{quoted} ]; then',
            f'  sha="\\"$(sha256sum "$RAIDAR_WORKSPACE"/{quoted} | cut -d\' \' -f1)\\""',
            "else sha=null; fi",
            f'files_json+="${{files_json:+,}}\\"{relative}\\":$sha"',
        ]
    lines += [
        f'mkdir -p -- "$RAIDAR_LOGS_DIR"/{EVIDENCE_DIR.name}',
        f'cat > "$RAIDAR_LOGS_DIR"/{COMPONENT_REPORT} <<JSON',
        '{"kind":"raidar-components","workspace":"$RAIDAR_WORKSPACE",'
        '"workspace_files":{${files_json}},"components":[${RAIDAR_COMPONENT_SLUGS}]}',
        "JSON",
    ]
    return lines


def render_setup_script(
    *,
    support_files: Mapping[str, SupportFile],
    workspace_paths: Iterable[str],
    component_slugs: Iterable[str],
) -> str:
    """Render the whole ``setup.sh``; paths are validated so no quoting reaches JSON."""
    workspace_paths = sorted(set(workspace_paths))
    for relative in workspace_paths:
        _check_relative(relative, "workspace overlay")
    slugs = ",".join(f'"{slug}"' for slug in component_slugs)
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by raidar.components.runtime.setup_script; do not edit.",
        "set -uo pipefail",
        'RAIDAR_WORKSPACE="$(cd "$(dirname "$0")" && pwd)"',
        f'RAIDAR_LOGS_DIR="${{RAIDAR_LOGS_DIR:-{EVIDENCE_DIR.parent}}}"',
        f'RAIDAR_COMPONENT_ROOT="${{RAIDAR_COMPONENT_ROOT:-{COMPONENT_ROOT}}}"',
        "export RAIDAR_COMPONENT_ROOT",
        f"RAIDAR_COMPONENT_SLUGS={shlex.quote(slugs)}",
        reset_body(),
        "# ---- 3. component support files (outside the workspace) ------------------",
    ]
    for path in sorted(support_files):
        lines += _materialise(path, support_files[path])
    lines.append("# ---- 4. workspace evidence at step start ---------------------------------")
    lines += _workspace_evidence(workspace_paths)
    lines += [
        "# ---- 5. never leave this script in the agent's workspace ----------------",
        "# The upload overwrote any agent-authored setup.sh; the agent-end reaper",
        "# stashed that file, so it is put back instead of being deleted (F3).",
        f'RAIDAR_AGENT_SETUP_STASH="${{RAIDAR_AGENT_SETUP_STASH:-{AGENT_SETUP_STASH}}}"',
        'if [ "${RAIDAR_RESET_KEEP_SELF:-0}" != "1" ]; then',
        '  if [ -f "$RAIDAR_AGENT_SETUP_STASH" ]; then',
        '    cp -- "$RAIDAR_AGENT_SETUP_STASH" "$0" 2>/dev/null || rm -f -- "$0" 2>/dev/null',
        '  else rm -f -- "$0" 2>/dev/null; fi',
        "fi",
        "exit 0",
        "",
    ]
    return "\n".join(lines)
